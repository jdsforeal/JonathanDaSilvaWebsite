function getResponsiveImageInfo(path) {

    if (!path) {
        return {
            master: "",
            small: "",
            masterWidth: 0,
            smallWidth: 0
        };
    }

    return (
        RESPONSIVE_IMAGE_MAP[path] || {
            master: path,
            small: path,
            masterWidth: 0,
            smallWidth: 0
        }
    );

}


function applyResponsiveImage(
    imageElement,
    logicalPath,
    sizes = "100vw"
) {

    if (!imageElement) {
        return;
    }

    const info =
        getResponsiveImageInfo(
            logicalPath
        );

    imageElement.sizes =
        sizes;

    if (
        info.small &&
        info.master &&
        info.smallWidth > 0 &&
        info.masterWidth > info.smallWidth
    ) {

        imageElement.srcset =
            `${info.small} ${info.smallWidth}w, ` +
            `${info.master} ${info.masterWidth}w`;

    } else {

        imageElement.removeAttribute(
            "srcset"
        );

    }

    imageElement.src =
        info.master || logicalPath;

}

